/** 문자열 배열을 {w, h, bits} 형태로 변환한다. */
export function parseSprite(rows) {
  const h = rows.length;
  const w = rows[0].length;
  const bits = new Uint8Array(w * h);
  rows.forEach((row, y) => {
    for (let x = 0; x < w; x++) bits[y * w + x] = row[x] === '#' ? 1 : 0;
  });
  return { w, h, bits };
}

/** 양수/음수 프레임을 안전하게 순환시킨다. */
export function spriteFrame(frame, count) {
  const value = Number.isFinite(frame) ? Math.trunc(frame) : 0;
  return ((value % count) + count) % count;
}

const cache = new Map();
/** 기존 {w, h, bits} 계약 유지. 두 번째 인자를 주면 디지몬 포즈를 고른다. */
export function getSprite(name, frame = 0) {
  const frames = DIGIMON_SPRITE_FRAMES[name];
  const index = frames ? spriteFrame(frame, frames.length) : 0;
  const key = `${name}:${index}`;
  if (cache.has(key)) return cache.get(key);
  const rows = frames ? frames[index] : ICON_SPRITES[name];
  if (!rows) throw new Error(`unknown sprite: ${name}`);
  const parsed = parseSprite(rows);
  cache.set(key, parsed);
  return parsed;
}
